def public_fact_payload(facts_file: Path) -> dict:
    raw = facts_file.read_bytes()
    data = yaml.safe_load(raw)
    if not isinstance(data, dict) or data.get("schema_version") != 1:
        raise ValueError(f"unsupported business-facts schema: {facts_file}")
    identity = data["identity"]
    phone_digits = re.sub(r"\D", "", str(identity["phone"]))
    if len(phone_digits) == 10:
        phone_e164 = f"+1{phone_digits}"
    elif len(phone_digits) == 11 and phone_digits.startswith("1"):
        phone_e164 = f"+{phone_digits}"
    else:
        raise ValueError(f"unsupported US phone format in {facts_file}")
    service = data["service_area"]
    pricing = data["pricing"]
    guarantee = data["guarantee"]
    public_statement = str(
        guarantee.get("public_statement") or guarantee["summary"]
    ).strip()
    claims = data["claim_gates"]
    hours = data["hours"]
    services = data["services"]
    fleet_discount = data["fleet_discount"]
    facts = {
        "businessName": identity["name"],
        "phoneDisplay": identity["phone"],
        "phoneE164": phone_e164,
        "serviceAreaBase": service["base"],
        "serviceAreaRadiusMiles": service["radius_miles"],
        "serviceAreaPlaces": service["places"],
        "pricing": {
            "fullInterior": pricing["one_time"]["full_interior"]["price"],
            "fullInteriorHours": pricing["one_time"]["full_interior"]["duration_hours"],
            "ultimateInterior": pricing["one_time"]["ultimate_interior"]["price"],
            "ultimateInteriorHours": pricing["one_time"]["ultimate_interior"]["duration_hours"],
            "monthly": pricing["membership_per_visit"]["monthly"],
            "biMonthly": pricing["membership_per_visit"]["bi_monthly"],
            "quarterly": pricing["membership_per_visit"]["quarterly"],
            "neighborDiscount": pricing["neighbor_discount"],
        },
        "guarantee": {
            "name": guarantee["name"],
            "summary": guarantee["summary"],
            "publicStatement": public_statement,
            # Internal policy only. The published guarantee carries no time
            # limit -- terms-of-service and cancellation-refund-policy commit to
            # "before we leave, or as soon as reasonably possible after the
            # appointment", so no public surface may narrow that to a window.
            "remedyWindowHours": guarantee["remedy_window_hours"],
        },
        "publicReviewCountAllowed": bool(
            claims["review_count_public_claim"]["allowed"]
        ),
        "equipment": {
            "steamerOwned": bool(data["equipment"]["steamer"]["owned"]),
            "ozoneOwned": bool(data["equipment"]["ozone_machine"]["owned"]),
        },
        "hours": {
            "days": hours["days"],
            "opens": hours["opens"],
            "closes": hours["closes"],
        },
        "services": {
            "durationHoursMin": services["duration_hours"]["min"],
            "durationHoursMax": services["duration_hours"]["max"],
            "offered": services["offered"],
            "exteriorAddOn": services["exterior_add_on"],
            "notOffered": services["not_offered"],
        },
        "fleetDiscount": {
            "available": bool(fleet_discount["available"]),
            "appliesTo": fleet_discount["applies_to"],
        },
    }
    # Public drift binds to the derived payload, so review metadata and YAML
    # formatting do not invalidate every rendered surface. FactSnapshot's
    # source_hash deliberately remains a raw-byte hash in facts.load_snapshot:
    # immutable packages must still bind to the exact canonical file state.
    return {
        "sourceHash": hashlib.sha256(canonical_json(facts).encode("utf-8")).hexdigest(),
        "facts": facts,
    }


def _render_typescript(payload: dict) -> str:
    value = json.dumps(payload, ensure_ascii=False, sort_keys=True, indent=2)
    return (
        "// Generated by fmd-seo-engine from business-facts.yaml. Do not hand-edit.\n"
        "// prettier-ignore\n"
        f"export const BUSINESS_FACTS_PAYLOAD = {value} as const;\n"
        "export const BUSINESS_FACTS = BUSINESS_FACTS_PAYLOAD.facts;\n"
        "export const BUSINESS_FACTS_SOURCE_HASH = BUSINESS_FACTS_PAYLOAD.sourceHash;\n"
    )


# Display names for the two priced one-time tiers. Binding is by the priced-tier
# key (fullInterior / ultimateInterior), never by services.offered[i]: reordering
# that list used to publish the $209 line under whoever happened to be first.
# A rename still moves the price line when the new name is listed here.
PRICED_TIER_NAMES = {
    "fullInterior": ("The Interior Reset", "Full Interior Detail"),
    "ultimateInterior": ("The Deep Interior Reset", "Ultimate Interior Detail"),
}


def _priced_tier_name(facts: dict, tier_key: str) -> str:
    """Return the display name bound to a priced tier, not a list position."""
    pricing = facts["pricing"]
    explicit = pricing.get(f"{tier_key}Name")
    if explicit:
        return str(explicit)
    offered = list(facts["services"]["offered"])
    for name in PRICED_TIER_NAMES[tier_key]:
        if name in offered:
            return name
    raise ValueError(
        f"services.offered must name the {tier_key} priced tier "
        f"({', '.join(PRICED_TIER_NAMES[tier_key])}); got {offered!r}"
    )


def _render_llms(payload: dict) -> str:
    facts = payload["facts"]
    pricing = facts["pricing"]
    places = ", ".join(facts["serviceAreaPlaces"])
    offered = facts["services"]["offered"]
    primary = _priced_tier_name(facts, "fullInterior")
    secondary = _priced_tier_name(facts, "ultimateInterior")
    return f"""# {facts['businessName']}

> Interior-first mobile car detailing serving Cleveland's eastern suburbs from {facts['serviceAreaBase']}.

## Verified facts

- Phone/text: {facts['phoneDisplay']}
- {primary}: From ${pricing['fullInterior']} (about {pricing['fullInteriorHours']} hours)
- {secondary}: From ${pricing['ultimateInterior']} (about {pricing['ultimateInteriorHours']} hours)
- Fresh Club: ${pricing['monthly']} monthly, ${pricing['biMonthly']} bi-monthly, ${pricing['quarterly']} quarterly per visit
- Guarantee: {facts['guarantee']['name']} — {facts['guarantee']['publicStatement']}
- Service area: {places}
- Hours: {', '.join(facts['hours']['days'])}, {facts['hours']['opens']}–{facts['hours']['closes']}
- Services: {', '.join(facts['services']['offered'])}; exterior add-on: {facts['services']['exteriorAddOn']}
- Typical duration: {facts['services']['durationHoursMin']}-{facts['services']['durationHoursMax']} hours
- Not offered: {', '.join(facts['services']['notOffered'])}
- Fleet and multi-car discounts: {'available' if facts['fleetDiscount']['available'] else 'not available'}

## Pages

- [Home](/)
- [Interior car detailing](/interior-detailing)
- [Mobile car detailing](/mobile-detailing)
- [Areas served](/areas)
- [Fleet](/fleet)
- [Boat](/boat)
- [Fresh Pro](/fresh-pro)
- [Fresh Assist](/chat)
- [Guides](/blog)
"""


def generate_site_fact_files(facts_file: Path, site_worktree: Path) -> dict:
    payload = public_fact_payload(facts_file)
    ts_path = site_worktree / "src" / "lib" / "business-facts.ts"
    llms_path = site_worktree / "public" / "llms.txt"
    ts_path.parent.mkdir(parents=True, exist_ok=True)
    llms_path.parent.mkdir(parents=True, exist_ok=True)
    ts_path.write_text(_render_typescript(payload), encoding="utf-8")
    llms_path.write_text(_render_llms(payload), encoding="utf-8")
    return {
        "source_hash": payload["sourceHash"],
        "generated_files": [str(ts_path), str(llms_path)],
        "payload": payload,
    }


def compare_public_facts(expected: dict, observed: dict) -> int:
    mismatches = int(expected.get("sourceHash") != observed.get("sourceHash"))
    expected_facts = expected.get("facts") or {}
    observed_facts = observed.get("facts") or {}
    keys = set(expected_facts) | set(observed_facts)
    mismatches += sum(expected_facts.get(key) != observed_facts.get(key) for key in keys)
    return mismatches


def verify_generated_fact_hash(
    facts_file: Path, generated_ts: Path, generated_llms: Path | None = None,
) -> dict:
    """Fail if either generated public fact surface diverges from authority."""
    expected_payload = public_fact_payload(facts_file)
    expected = expected_payload["sourceHash"]
    generated = generated_ts.read_text(encoding="utf-8")
    # Byte comparison against the renderer, mirroring the llms.txt check below.
    # Parsing BUSINESS_FACTS_PAYLOAD out with a regex left everything around
    # that literal unchecked -- including
    # `export const BUSINESS_FACTS = BUSINESS_FACTS_PAYLOAD.facts;`, which is
    # what CityPage.tsx, chat.ts and the MCP tools actually import. Rewriting
    # that export to a literal carrying a wrong phone number and a $999 price
    # still returned DONE.
    if generated != _render_typescript(expected_payload):
        observed_match = re.search(r'"sourceHash":\s*"([0-9a-f]{64})"', generated)
        observed = observed_match.group(1) if observed_match else None
        # Second, narrower assertion purely for the error message: it separates
        # "the facts moved" from "someone edited the file around the payload".
        raise ValueError(
            "generated facts payload mismatch with canonical projection: "
            f"{generated_ts} is not byte-identical to the renderer "
            f"(canonical hash={expected} site hash={observed})"
        )
    llms_path = generated_llms or generated_ts.parents[2] / "public" / "llms.txt"
    observed_llms = llms_path.read_text(encoding="utf-8")
    expected_llms = _render_llms(expected_payload)
    if observed_llms != expected_llms:
        raise ValueError("generated public/llms.txt mismatch with canonical projection")
    return {
        "command": "facts-check",
        "status": "DONE",
        "source_hash": expected,
        "generated_file": str(generated_ts),
        "generated_files": [str(generated_ts), str(llms_path)],
    }


def fetch_public_facts(url: str) -> dict:
    request = urllib.request.Request(
        url,
        headers={"User-Agent": "fmd-seo-site-facts/1"},
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        if response.status != 200:
            raise RuntimeError(f"site facts endpoint returned HTTP {response.status}")
        return json.loads(response.read().decode("utf-8"))


def fetch_public_text(url: str) -> str:
    request = urllib.request.Request(url, headers={"User-Agent": "fmd-seo-site-facts/1"})
    with urllib.request.urlopen(request, timeout=30) as response:
        if response.status != 200:
            raise RuntimeError(f"site fact surface returned HTTP {response.status}: {url}")
        return response.read().decode("utf-8", errors="replace")


def _payload_value(payload: dict, dotted_key: str):
    value = payload.get("facts") or {}
    for part in dotted_key.split("."):
        if not isinstance(value, dict) or part not in value:
            raise ValueError(f"unknown public fact surface key: {dotted_key}")
        value = value[part]
    return value


def compare_fact_surface(expected: dict, html: str, required: list[str]) -> list[str]:
    """Verify a rendered page advertises its fact hash and required public values."""
    missing: list[str] = []
    if expected["sourceHash"] not in html:
        missing.append("sourceHash")
    for key in required:
        value = str(_payload_value(expected, key))
        if value not in html:
            missing.append(key)
    return missing


def sync_public_facts(
    config: dict,
    brain: Brain,
    *,
    observations_dir: Path | None = None,
    fetcher: Callable[[str], dict] = fetch_public_facts,
    surface_fetcher: Callable[[str], str] = fetch_public_text,
) -> dict:
    """Compare the deployed public facts surface with the canonical YAML.

    Missing configuration is an explicit no-op so local/offline sync remains
    usable. Fetch failures deliberately propagate to the caller, which records
    them in ``sync.health``; a successful fetch always records drift, including
    the clean zero case.
    """
    site = config.get("site") or {}
    url = site.get("facts_url")
    facts_file = (config.get("paths") or {}).get("facts_file")
    if not url or not facts_file:
        return {"status": "skipped", "reason": "site facts sync not configured"}

    expected = public_fact_payload(Path(facts_file))
    observed = fetcher(url)
    mismatches = compare_public_facts(expected, observed)
    surface_results: list[dict] = []
    for surface in site.get("fact_surfaces") or []:
        surface_url = str(surface["url"])
        html = surface_fetcher(surface_url)
        missing = compare_fact_surface(expected, html, list(surface.get("required") or []))
        mismatches += len(missing)
        surface_results.append({"url": surface_url, "missing": missing})
    record_observation(
        brain,
        "site.facts_drift",
        {"fact_mismatches": mismatches},
        fulfillment="engine_api",
        source=url,
        note=(f"expected source hash {expected['sourceHash']}; "
              f"rendered surfaces checked {len(surface_results)}"),
        directory=observations_dir,
    )
    return {
        "status": "fetched",
        "url": url,
        "fact_mismatches": mismatches,
        "surfaces": surface_results,
    }
